"""
Step 8 — dataset report (counts, balance, duplicates, leakage, licences).

    backend/.venv/Scripts/python scripts/vision/dataset_report.py   → metadata/dataset_report.json + .md

train_test_leakage_count = test images whose difference hash is within NEAR_DUP_BITS of any training image
(should be 0 because splits are group-aware; any non-zero value is listed for review).
"""
import json
import sys
from collections import Counter, defaultdict

import numpy as np

from common import DATASET_VERSION, METADATA, VISION, read_csv
from detect_duplicates import NEAR_DUP_BITS


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    rows = [r for r in read_csv(METADATA / "manifest.csv") if r["split"] not in ("", "not_selected")]
    hashes = {c["sha1"][:16]: int(c["dhash"], 16) for c in read_csv(METADATA / "candidates.csv")}
    dup = json.loads((METADATA / "duplicate_stats.json").read_text(encoding="utf-8"))

    train = np.array([hashes[r["image_id"]] for r in rows if r["split"] == "train"], dtype=np.uint64)
    leaks = []
    for r in rows:
        if r["split"] in ("test", "validation"):
            h = np.uint64(hashes[r["image_id"]])
            if train.size and int(np.bitwise_count(train ^ h).min()) <= NEAR_DUP_BITS:
                leaks.append({"image_id": r["image_id"], "label": r["label"], "split": r["split"]})

    per_class = defaultdict(Counter)
    per_source = defaultdict(Counter)
    for r in rows:
        per_class[r["label"]][r["split"]] += 1
        per_source[r["source_dataset"]][r["split"]] += 1
    report = {
        "dataset_version": DATASET_VERSION,
        "images": len(rows),
        "classes": len([c for c in per_class if c != "ood_test"]),
        "split_counts": dict(Counter(r["split"] for r in rows)),
        "per_class": {k: dict(v) for k, v in sorted(per_class.items())},
        "per_source": {k: dict(v) for k, v in sorted(per_source.items())},
        "licenses": dict(Counter(r["license"] for r in rows)),
        "duplicate_count": dup["exact_duplicates"],
        "near_duplicate_count": dup["near_duplicate_pairs"],
        "label_conflict_groups": dup["label_conflict_groups"],
        "train_test_leakage_count": len([l for l in leaks if l["split"] == "test"]),
        "train_validation_leakage_count": len([l for l in leaks if l["split"] == "validation"]),
        "leak_examples": leaks[:20],
    }
    (METADATA / "dataset_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    lines = [f"# Vision dataset report ({DATASET_VERSION})", "",
             f"- images: {report['images']} · classes: {report['classes']} · splits: {report['split_counts']}",
             f"- exact duplicates removed: {report['duplicate_count']} · near-duplicate pairs grouped: {report['near_duplicate_count']}",
             f"- label-conflict groups dropped: {report['label_conflict_groups']}",
             f"- train↔test leakage: {report['train_test_leakage_count']} · train↔validation leakage: {report['train_validation_leakage_count']}",
             "", "| label | train | validation | test | ood_test |", "|---|---|---|---|---|"]
    for label, c in report["per_class"].items():
        lines.append(f"| {label} | {c.get('train', 0)} | {c.get('validation', 0)} | {c.get('test', 0)} | {c.get('ood_test', 0)} |")
    lines += ["", "| source | train | validation | test | ood_test |", "|---|---|---|---|---|"]
    for source, c in report["per_source"].items():
        lines.append(f"| {source} | {c.get('train', 0)} | {c.get('validation', 0)} | {c.get('test', 0)} | {c.get('ood_test', 0)} |")
    (METADATA / "dataset_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    write_sources_md(rows)
    print("\n".join(lines[:6]))


def write_sources_md(rows):
    """datasets/vision/SOURCES.md — one section per source actually used, with licence and real image counts."""
    sources = {r["dataset_key"]: r for r in read_csv(METADATA / "sources.csv")}
    licenses = {r["dataset_key"]: r for r in read_csv(METADATA / "licenses.csv")}
    used = defaultdict(list)
    for r in rows:
        used[r["source_dataset"]].append(r)
    md = [f"# Vision dataset sources ({DATASET_VERSION})", "",
          "Generated by `scripts/vision/dataset_report.py` from metadata/sources.csv, licenses.csv and manifest.csv.",
          "Only CC0 1.0 / CC BY 4.0 sources are used. No images were scraped from search engines or social media.", ""]
    for key, items in sorted(used.items()):
        src, lic = sources.get(key, {}), licenses.get(key, {})
        labels = Counter(r["label"] for r in items)
        md += [f"## {src.get('dataset_name', key)}", "",
               f"- dataset_key: `{key}`",
               f"- source_url: {src.get('source_url', '')}",
               f"- license: {lic.get('license', '')} ({lic.get('license_url', '')})",
               f"- citation: {lic.get('citation', '')}",
               f"- download_date: {src.get('download_date', '')}",
               f"- image_style: {src.get('image_style', '')}",
               f"- number_of_images used: {len(items)} ({dict(Counter(r['split'] for r in items))})",
               f"- classes: {', '.join(f'{k} ({v})' for k, v in sorted(labels.items()))}",
               f"- usage_restrictions: {lic.get('usage_restrictions', '')}", ""]
    (VISION / "SOURCES.md").write_text("\n".join(md), encoding="utf-8")


if __name__ == "__main__":
    main()
